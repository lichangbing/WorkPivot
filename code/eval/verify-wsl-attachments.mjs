import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const base = 'http://127.0.0.1:39986/api';
const auth = await fetch(base + '/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'attachment-test', password: 'WorkPivot-local-test-2026!' }) });
assert(auth.ok);
const { token } = await auth.json();
const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' };
const tasks = await (await fetch(base + '/tasks', { headers })).json();
const task = tasks.tasks.find(t => t.name === '上传与消息引用验收'); assert(task);
const url = base + '/tasks/' + task.id;
const { files } = await (await fetch(url + '/files', { headers })).json();
const file = files.find(f => f.name === '附件联调.csv'); assert(file, 'browser-uploaded file survives service restart');
const downloaded = Buffer.from(await (await fetch(url + '/file-versions/' + file.id, { headers })).arrayBuffer());
assert(downloaded.equals(await readFile(new URL('../../releases/deploy/artifacts/附件联调.csv', import.meta.url))));
const page = await (await fetch(url + '/conversation', { headers })).json();
assert(page.turns.some(t => t.events.some(e => e.attachments?.some(a => a.id === file.id))));
const removed = await fetch(url + '/files/' + file.documentId, { method: 'DELETE', headers, body: JSON.stringify({ revision: file.revision }) });
assert(removed.ok); assert.equal((await removed.json()).cleanupPending, false);
assert.equal((await fetch(url + '/file-versions/' + file.id, { headers })).status, 404);
const after = await (await fetch(url + '/conversation', { headers })).json();
assert(after.turns.some(t => t.events.some(e => e.attachments?.some(a => a.id === file.id && a.deleted && a.name === null))));
await fetch(base + '/auth/logout', { method: 'POST', headers });
console.log('WSL: browser-uploaded original survives restart; bytes match; history references persist; deletion clears original and redacts filename.');
