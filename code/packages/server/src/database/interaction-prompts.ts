export function interactionDynamicPrompt(input: {
  mode: 'manual' | 'auto';
  allowedScopes: string[];
  hasPlan: boolean;
  externalActions: boolean;
}): string {
  return [
    `当前执行模式：${input.mode === 'manual' ? '确认模式' : '自动模式'}。`,
    `本轮用户选择的记忆层级：${input.allowedScopes.length ? input.allowedScopes.join('、') : '无'}。`,
    input.hasPlan ? '当前任务已有可审阅计划，计划变化会撤销旧批准。' : '当前任务尚无计划；若任务复杂，先建立计划。',
    input.externalActions ? '任务包含外部动作，高风险步骤必须逐次确认，不能使用永久豁免。' : '当前未声明外部动作；实际出现外部动作时仍必须确认。',
  ].join('\n');
}
